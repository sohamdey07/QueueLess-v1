/**
 * Create a short-lived authorization token for password reset (10-15 minute expiry)
 */
const createPasswordResetToken = async (email) => {
    const normalizedEmail = email.toLowerCase();
    const resetToken = crypto.randomBytes(32).toString("hex");

    // Map token -> email
    await redisClient.set(
        `ql:password-reset:${resetToken}`,
        normalizedEmail,
        { EX: PASSWORD_RESET_TOKEN_EXPIRY }
    );

    // Optional reverse lookup / audit key
    await redisClient.set(
        `ql:password-reset:${normalizedEmail}:${resetToken}`,
        "1",
        { EX: PASSWORD_RESET_TOKEN_EXPIRY }
    );

    return resetToken;
};

/**
 * Retrieve the email associated with a password reset token
 */
const getPasswordResetTokenEmail = async (resetToken) => {
    if (!resetToken) return null;
    return await redisClient.get(`ql:password-reset:${resetToken}`);
};

/**
 * Invalidate / delete password reset token so it cannot be reused
 */
const deletePasswordResetToken = async (resetToken, email) => {
    if (resetToken) {
        await redisClient.del(`ql:password-reset:${resetToken}`);
    }
    if (email && resetToken) {
        await redisClient.del(`ql:password-reset:${email.toLowerCase()}:${resetToken}`);
    }
};

export {
    storeOTP,
    verifyOTP,
    storePasswordResetOTP,
    verifyPasswordResetOTP,
    createPasswordResetToken,
    getPasswordResetTokenEmail,
    deletePasswordResetToken
};